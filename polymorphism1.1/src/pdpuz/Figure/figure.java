package pdpuz.Figure;

public class figure {

    public int perimeter(int a) {
        return 4 * a;
    }

    public int perimeter(int a, int b) {
        return 2 * (a + b);
    }

    public int perimeter(int a, int b, int c) {
        return a + b + c;
    }


    public int perimeter(int a, int b, int c, int d, int e) {
        return a + b + c + d + e;
    }

}
