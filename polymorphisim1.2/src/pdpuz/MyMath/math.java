package pdpuz.MyMath;

public class math {

    public int add(int a, int b) {
        return a + b;
    }

    public double add(double a, double b) {
        return a + b;
    }

    public double add(double a, int b) {
        return a + b;
    }

    public String add(String text, int number) {
        return text + number;
    }

    public String add(String text, double number) {
        return text + number;
    }

    public String add(String text1, String text2) {
        return text1 + text2;
    }
}
